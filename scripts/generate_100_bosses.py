colors_easy = ["#00f3ff", "#33ccff", "#55e6c1", "#26de81", "#fed330", "#a55eea"]
colors_normal = ["#00f3ff", "#ff7700", "#ffd000", "#ff0055", "#00ffaa", "#a55eea"]
colors_hard = ["#ff0055", "#ff3838", "#ff5e57", "#ff9f1a", "#b844ff", "#ff1493"]
colors_hardcorez = ["#b844ff", "#ff00ff", "#ff0055", "#00f3ff", "#ffffff", "#ffd700"]

def build_catalog():
    bosses = []
    
    # 1. Easy (1 to 25)
    for i in range(25):
        boss_id = i + 1
        is_big = (i % 2 == 1) # alternate mini and big
        if is_big:
            name, title = easy_bigboss_names[(i // 2) % len(easy_bigboss_names)]
            hp = 110 + (i * 3)
            attack = "curtain_fan" if i % 4 == 1 else "railgun_laser"
        else:
            name, title = easy_miniboss_names[(i // 2) % len(easy_miniboss_names)]
            hp = 45 + (i * 2)
            attack = "plasma_twin" if i % 4 == 0 else "escort_shield"
        bosses.append({
            "id": boss_id,
            "tier": "easy",
            "name": name,
            "title": title,
            "isBig": is_big,
            "color": colors_easy[i % len(colors_easy)],
            "baseHp": hp,
            "attack": attack
        })

    # 2. Normal (26 to 50)
    for i in range(25):
        boss_id = 26 + i
        is_big = (i % 2 == 1)
        if is_big:
            name, title = normal_bigboss_names[(i // 2) % len(normal_bigboss_names)]
            hp = 180 + (i * 5)
            attack = "railgun_laser" if i % 4 == 1 else "curtain_fan"
        else:
            name, title = normal_miniboss_names[(i // 2) % len(normal_miniboss_names)]
            hp = 65 + (i * 3)
            attack = "spiral_danmaku" if i % 4 == 0 else "escort_shield"
        bosses.append({
            "id": boss_id,
            "tier": "normal",
            "name": name,
            "title": title,
            "isBig": is_big,
            "color": colors_normal[i % len(colors_normal)],
            "baseHp": hp,
            "attack": attack
        })

    # 3. Hard (51 to 75)
    for i in range(25):
        boss_id = 51 + i
        is_big = (i % 2 == 1)
        if is_big:
            name, title = hard_bigboss_names[(i // 2) % len(hard_bigboss_names)]
            hp = 250 + (i * 8)
            attack = "railgun_laser" if i % 2 == 1 else "curtain_fan"
        else:
            name, title = hard_miniboss_names[(i // 2) % len(hard_miniboss_names)]
            hp = 95 + (i * 4)
            attack = "spiral_danmaku" if i % 2 == 0 else "rapid_burst"
        bosses.append({
            "id": boss_id,
            "tier": "hard",
            "name": name,
            "title": title,
            "isBig": is_big,
            "color": colors_hard[i % len(colors_hard)],
            "baseHp": hp,
            "attack": attack
        })

    # 4. Hardcorez (76 to 100)
    for i in range(25):
        boss_id = 76 + i
        is_big = (i % 2 == 1)
        if is_big:
            name, title = hardcorez_bigboss_names[(i // 2) % len(hardcorez_bigboss_names)]
            hp = 360 + (i * 12)
            attack = "curtain_fan" if i % 2 == 1 else "railgun_laser"
        else:
            name, title = hardcorez_miniboss_names[(i // 2) % len(hardcorez_miniboss_names)]
            hp = 140 + (i * 6)
            attack = "spiral_danmaku" if i % 2 == 0 else "rapid_burst"
        bosses.append({
            "id": boss_id,
            "tier": "hardcorez",
            "name": name,
            "title": title,
            "isBig": is_big,
            "color": colors_hardcorez[i % len(colors_hardcorez)],
            "baseHp": hp,
            "attack": attack
        })

    return bosses

