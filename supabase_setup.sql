-- 1. Buat Tabel Leaderboard
CREATE TABLE IF NOT EXISTS public.leaderboard (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(10) NOT NULL,
  score INTEGER NOT NULL,
  time INTEGER NOT NULL DEFAULT 0,
  formatted_time VARCHAR(10) NOT NULL DEFAULT '00:00',
  diff VARCHAR(15) NOT NULL DEFAULT 'normal',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Index untuk Query Top 10 Berkecepatan Tinggi
CREATE INDEX IF NOT EXISTS idx_leaderboard_score_desc ON public.leaderboard (score DESC);

-- 3. Aktifkan Row Level Security (RLS) untuk Keamanan Database
ALTER TABLE public.leaderboard ENABLE ROW LEVEL SECURITY;

-- 4. Policy: Siapa Saja Boleh Melihat Ranking (Public Read / Select)
DROP POLICY IF EXISTS "Allow public read leaderboard" ON public.leaderboard;
CREATE POLICY "Allow public read leaderboard"
ON public.leaderboard
FOR SELECT
USING (true);

-- 5. Policy: Siapa Saja Boleh Mengirim Skor Baru (Public Insert)
DROP POLICY IF EXISTS "Allow public insert leaderboard" ON public.leaderboard;
CREATE POLICY "Allow public insert leaderboard"
ON public.leaderboard
FOR INSERT
WITH CHECK (true);

